import { GITHUB_CONFIG, CACHE_CONFIG } from "@/lib/constants";
import reposFallback from "@/lib/repos-fallback.json";

function headers(): HeadersInit {
  const h: HeadersInit = {
    Accept: GITHUB_CONFIG.ACCEPT_HEADER,
    "X-GitHub-Api-Version": GITHUB_CONFIG.API_VERSION,
  };
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (token) {
    (h as Record<string, string>).Authorization = `Bearer ${token}`;
  }
  return h;
}

// Never let a GitHub outage or a rate-limit take the whole page down.
async function get<T>(path: string, fallback: T): Promise<T> {
  try {
    const url = path.startsWith("http") ? path : `${GITHUB_CONFIG.API_BASE_URL}${path}`;
    const res = await fetch(url, {
      headers: headers(),
      next: { revalidate: CACHE_CONFIG.GITHUB_REVALIDATE_SECONDS },
    });
    if (!res.ok) {
      console.error(`GitHub ${path} -> ${res.status} ${res.statusText}`);
      return fallback;
    }
    return (await res.json()) as T;
  } catch (err) {
    console.error(`GitHub ${path} failed`, err);
    return fallback;
  }
}

export function getProfile(user: string) {
  return get<Profile | null>(`/users/${user}`, null);
}

